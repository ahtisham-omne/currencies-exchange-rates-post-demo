const DND_LIST_KPI = 'gl-list-kpi'

/* ─── KPI definition type (mirrors the Chart of Accounts / Partners module) ─── */
export interface GlKpiDefinition {
  key: string
  label: string
  category: string
  subtitle: string
  tooltip?: string
  // Navigable KPIs point at a specific account or entry - their value renders as
  // a link that opens the target.
  navigable?: boolean
}

/* ─── The General Ledger KPI set ───
//
// The ledger is the stream of every posting, not a set of balances, so these
// describe activity *within the selected accounting period* rather than stating a
// current position the way the chart's cards do. The period selector governs
// them; there is no rolling window here to disagree with it.
//
// Three cards are deliberately absent because double-entry fixes them and a fixed
// number can never be worth a glance: total debit and total credit as separate
// cards (always equal, so activity is stated once) and net movement across the
// whole ledger (always zero). The busiest account is out for the practical
// version of the same reason - in most businesses it names receivables or
// payables every single period.
//
// Manual journal entries earn their place by being the one number here worth
// watching: everything else arrives from a module, so this is the one figure a
// person authored directly, and a high count is a cue to look closer. */
// Labels and tooltips in Mahad's copy of 2026-10-14. "Total debits" was "Total
// activity": the figure is the period's debits, so the card says so.
export const ALL_GL_KPIS: GlKpiDefinition[] = [
  { key: 'total_activity', label: 'Total debits', category: 'Activity', subtitle: 'Value posted this period', tooltip: 'Sum of all debits posted in the selected period, which matches total credits.' },
  { key: 'postings', label: 'Postings', category: 'Activity', subtitle: 'Individual debit or credit lines', tooltip: 'Number of debit and credit lines posted in the selected period.' },
  { key: 'largest_posting', label: 'Largest posting', category: 'Activity', subtitle: 'Biggest single line', tooltip: 'Largest single debit or credit line posted in the selected period.', navigable: true },
  { key: 'manual_journal_entries', label: 'Manual journal entries', category: 'Review', subtitle: 'Created by hand', tooltip: 'Journal entries created directly in the general ledger rather than generated by another module.' },
]

/* Default active KPIs - the full curated set. */
export const DEFAULT_GL_KPIS = ALL_GL_KPIS.map(k => k.key)

/* A KPI that points at something the user can open. */
export interface GlKpiTarget { kind: 'account' | 'entry'; id: string }

/* ─── Precomputed stats bag built by the page over the period's postings ─── */
export interface GlKpiCtx {
  stats: {
    /** Value posted over the period. Stated once, since debits equal credits. */
    totalActivity: number
    postingCount: number
    /** Distinct entries, not postings: a manual entry is one document to review
     *  however many lines it carries. */
    manualEntryCount: number
    largestPosting: { jeNumber: string; label: string; value: number } | null
  }
  base: string
  /** The accounting period the cards describe, named as "Aug FY2026". */
  periodLabel: string
}

// KPI cards print the figure in full. Abbreviating to "$5.9M" rounded away the
// difference between a card and the ledger beneath it, so the two could not be
// reconciled by eye even when they agreed exactly.
export function computeGlKpiValue(key: string, ctx: GlKpiCtx): string {
  const { stats, base } = ctx
  switch (key) {
    case 'total_activity': return fmtCurrency(stats.totalActivity, base)
    case 'postings': return fmtNumber(stats.postingCount)
    case 'manual_journal_entries': return fmtNumber(stats.manualEntryCount)
    case 'largest_posting': return stats.largestPosting ? fmtCurrency(stats.largestPosting.value, base) : '-'
    default: return '–'
  }
}

/* Resolve a navigable KPI to the account or entry it should open. */
export function glKpiTarget(key: string, ctx: GlKpiCtx): GlKpiTarget | null {
  const { stats } = ctx
  if (key === 'largest_posting' && stats.largestPosting) return { kind: 'entry', id: stats.largestPosting.jeNumber }
  return null
}

/* A KPI card carries no icon, the same as the chart's cards: there is no symbol
   for "value posted this period", so whatever was drawn there stood in for the
   subject rather than the figure and told a reader nothing the label had not.
   The category icons below stay, because they group a list. */
function CategoryIcon({ category }: { category: string }) {
  switch (category) {
    case 'Volume': return <Receipt className="w-4 h-4 text-muted-foreground" />
    case 'Coverage': return <Layers className="w-4 h-4 text-muted-foreground" />
    case 'By Category': return <ChartColumn className="w-4 h-4 text-muted-foreground" />
    case 'Activity': return <TrendingUp className="w-4 h-4 text-muted-foreground" />
    default: return <ChartColumn className="w-4 h-4 text-muted-foreground" />
  }
}

/* ─── Draggable on-page KPI card ─── */
function DraggableListKpiCard({ index, label, value, tooltip, moveCard, onRemove, onOpen }: {
  index: number; label: string; value: string; tooltip?: string
  moveCard: (from: number, to: number) => void; onRemove?: () => void; onOpen?: () => void
}) {
  const ref = useRef<HTMLDivElement>(null)
  const headerRef = useRef<HTMLDivElement>(null)

  const [{ isDragging }, drag, preview] = useDrag({
    type: DND_LIST_KPI,
    item: () => ({ index }),
    collect: (monitor) => ({ isDragging: monitor.isDragging() }),
  })

  const [{ isOver }, drop] = useDrop({
    accept: DND_LIST_KPI,
    hover(item: { index: number }, monitor) {
      if (!ref.current) return
      const dragIndex = item.index
      const hoverIndex = index
      if (dragIndex === hoverIndex) return
      const hoverRect = ref.current.getBoundingClientRect()
      const hoverMiddleX = (hoverRect.right - hoverRect.left) / 2
      const hoverMiddleY = (hoverRect.bottom - hoverRect.top) / 2
      const clientOffset = monitor.getClientOffset()
      if (!clientOffset) return
      const hoverClientX = clientOffset.x - hoverRect.left
      const hoverClientY = clientOffset.y - hoverRect.top
      if (dragIndex < hoverIndex && hoverClientY < hoverMiddleY && hoverClientX < hoverMiddleX) return
      if (dragIndex > hoverIndex && hoverClientY > hoverMiddleY && hoverClientX > hoverMiddleX) return
      moveCard(dragIndex, hoverIndex)
      item.index = hoverIndex
    },
    collect: (monitor) => ({ isOver: monitor.isOver() }),
  })

  preview(drop(ref))
  drag(headerRef)

  if (isDragging) {
    return <div ref={ref} className="rounded-lg border border-dashed border-primary/20 bg-primary/[0.02] min-h-[52px] pointer-events-none" />
  }

  return (
    <div
      ref={ref}
      className={cn('border rounded-lg bg-white group relative min-w-0 transition-all duration-200 overflow-hidden',
        isOver
          ? 'border-primary/30 bg-primary/[0.03] shadow-[0_0_0_2px_rgba(10,119,255,0.08)] scale-[1.02]'
          : 'border-border hover:-translate-y-[1px] hover:border-[#93C5FD] hover:shadow-[0_2px_8px_-3px_rgba(10,119,255,0.06)]')}
    >
      {isOver && <div className="absolute inset-0 rounded-lg bg-primary/[0.02] pointer-events-none" />}
      <div className="px-3 py-2">
        {/* Label row = drag handle */}
        <div
          ref={headerRef}
          className="flex items-center justify-between gap-1 mb-1 cursor-grab active:cursor-grabbing select-none group/kpihdr"
        >
          <div className="flex items-center gap-1 min-w-0">
            <p className="text-xs text-slate-500 whitespace-nowrap" style={{ fontWeight: 500 }}>{label}</p>
            {tooltip && (
              <Tooltip side="bottom" content={<span className="block max-w-[220px]">{tooltip}</span>}>
                <button type="button" className="inline-flex shrink-0" tabIndex={-1} onClick={(e) => e.stopPropagation()}>
                  <Info className="w-3 h-3 text-slate-300 hover:text-slate-400 transition-colors cursor-help" />
                </button>
              </Tooltip>
            )}
          </div>
          <GripVertical className="w-3.5 h-3.5 shrink-0 text-slate-500 opacity-0 group-hover/kpihdr:opacity-100 transition-opacity duration-150 pointer-events-none" />
        </div>
        {/* Value - navigable KPIs render as a link that opens the target. Kept
            neutral (no blue); the dotted underline + arrow signal it's openable. */}
        <div className="flex items-baseline gap-1.5 min-w-0">
          {onOpen && value !== '-' ? (
            <button
              type="button"
              onClick={(e) => { e.stopPropagation(); onOpen() }}
              className="group/kpival inline-flex items-baseline gap-1 text-15 text-slate-700 hover:text-slate-900 tracking-tight truncate max-w-full text-left transition-colors cursor-pointer"
              style={{ fontWeight: 600, lineHeight: 1.15 }}
              title={`Open ${value}`}
            >
              <span className="truncate underline decoration-slate-300 decoration-dotted underline-offset-[3px] group-hover/kpival:decoration-slate-400">{value}</span>
              <ArrowUpRight className="w-3 h-3 text-slate-400 shrink-0 group-hover/kpival:text-slate-600 transition-colors" />
            </button>
          ) : (
            <p className="text-15 text-slate-700 tracking-tight truncate max-w-full cursor-text select-text" style={{ fontWeight: 600, lineHeight: 1.15 }}>{value}</p>
          )}
        </div>
      </div>
      {/* Remove button */}
      {onRemove && (
        <button
          onClick={(e) => { e.stopPropagation(); onRemove() }}
          className="absolute bottom-1 right-1 opacity-0 group-hover:opacity-100 transition-all duration-150 p-1 rounded cursor-pointer hover:bg-red-50 z-10"
          title={`Remove ${label}`}
        >
          <Trash2 className="w-3 h-3 text-slate-400 hover:text-red-500" />
        </button>
      )}
    </div>
  )
}

/* ─── On-page "Performance Insights" row ─── */
export function PerformanceInsights({
  ctx, activeKpis, setActiveKpis, onOpenPanel, onReset, lastRefreshed, onRefresh, onNavigate,
}: {
  ctx: GlKpiCtx
  activeKpis: string[]
  setActiveKpis: (updater: (prev: string[]) => string[]) => void
  onOpenPanel: () => void
  onReset: () => void
  lastRefreshed: Date
  onRefresh: () => void
  onNavigate: (target: GlKpiTarget) => void
}) {
  const activeDefs = useMemo(
    () => activeKpis.map(k => ALL_GL_KPIS.find(d => d.key === k)).filter(Boolean) as GlKpiDefinition[],
    [activeKpis],
  )
  const moveKpi = (from: number, to: number) => setActiveKpis(prev => {
    const next = [...prev]
    const [moved] = next.splice(from, 1)
    next.splice(to, 0, moved)
    return next
  })
  const toggleKpi = (key: string) => setActiveKpis(prev => prev.includes(key) ? prev.filter(k => k !== key) : [...prev, key])
  const refreshedLabel = lastRefreshed.toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' })
  const isDefault = activeKpis.length === DEFAULT_GL_KPIS.length && activeKpis.every((k, i) => k === DEFAULT_GL_KPIS[i])

  // Match Cash Management: when no KPIs are active the whole shelf is hidden.
  // Re-entry is the persistent "Insights" button in the page toolbar.
  if (activeDefs.length === 0) return null

  return (
    <div className="mb-4">
      {/* Header row */}
      <div className="flex items-center justify-between mb-2.5">
        <div className="flex items-center gap-2">
          <span className="text-sm text-muted-foreground" style={{ fontWeight: 500 }}>Performance Insights</span>
          {/* Stated, not chosen. The page's own period selector is what moves
              these cards, so a second control here could only ever disagree with
              it - but the window still has to be named, or "this period" on four
              tooltips refers to nothing on screen. */}
          <span className="text-11 text-slate-500" style={{ fontWeight: 500 }}>{ctx.periodLabel}</span>
          <span className="text-slate-300">|</span>
          <span className="text-11 text-slate-400" style={{ fontWeight: 400 }}>Updated {refreshedLabel}</span>
          <button onClick={onRefresh} className="inline-flex items-center gap-1 text-11 text-primary hover:text-[#1D4ED8] transition-colors cursor-pointer" style={{ fontWeight: 500 }}>
            <RefreshCw className="w-3 h-3" /> Refresh
          </button>
        </div>
        <div className="flex items-center gap-2">
          {!isDefault && (
            <button onClick={onReset} className="inline-flex items-center gap-1.5 h-8 px-3 rounded-lg border border-border bg-white hover:bg-slate-50 text-slate-700 text-xs shadow-sm transition-all cursor-pointer" style={{ fontWeight: 500 }}>
              <RotateCcw className="w-3.5 h-3.5 text-slate-400" /> Reset
            </button>
          )}
          <button onClick={onOpenPanel} className="inline-flex items-center gap-1 text-11 hover:bg-muted/50 px-2 py-0.5 rounded-md transition-colors cursor-pointer" style={{ fontWeight: 500, color: 'hsl(var(--primary))' }}>
            <Plus className="w-3 h-3" /> Customize insights
          </button>
        </div>
      </div>

      {/* Draggable responsive grid */}
      <DndProvider backend={HTML5Backend}>
        <div className="grid gap-2.5" style={{ gridTemplateColumns: 'repeat(auto-fill, minmax(210px, 1fr))' }}>
          {activeDefs.map((kpi, idx) => {
            const target = kpi.navigable ? glKpiTarget(kpi.key, ctx) : null
            return (
              <DraggableListKpiCard
                key={kpi.key}
                index={idx}
                label={kpi.label}
                value={computeGlKpiValue(kpi.key, ctx)}
                tooltip={kpi.tooltip}
                moveCard={moveKpi}
                onRemove={() => toggleKpi(kpi.key)}
                onOpen={target ? () => onNavigate(target) : undefined}
              />
            )
          })}
        </div>
      </DndProvider>
    </div>
  )
}

/* ─── Insights drawer (KPI toggle panel) ─── */
export function KpiInsightsPanel({ open, onOpenChange, activeKpis, onToggleKpi, onReset, ctx }: {
  open: boolean
  onOpenChange: (open: boolean) => void
  activeKpis: string[]
  onToggleKpi: (key: string) => void
  onReset?: () => void
  ctx: GlKpiCtx
}) {
  const [searchQuery, setSearchQuery] = useState('')
  const isDefault = activeKpis.length === DEFAULT_GL_KPIS.length && activeKpis.every((k, i) => k === DEFAULT_GL_KPIS[i])

  const categories = useMemo(() => {
    const catMap = new Map<string, GlKpiDefinition[]>()
    for (const kpi of ALL_GL_KPIS) {
      const matches = !searchQuery ||
        kpi.label.toLowerCase().includes(searchQuery.toLowerCase()) ||
        kpi.category.toLowerCase().includes(searchQuery.toLowerCase())
      if (matches) {
        if (!catMap.has(kpi.category)) catMap.set(kpi.category, [])
        catMap.get(kpi.category)!.push(kpi)
      }
    }
    const cats: { name: string; kpis: GlKpiDefinition[] }[] = []
    catMap.forEach((kpis, name) => cats.push({ name, kpis }))
    return cats
  }, [searchQuery])

  // Counted against the catalogue rather than against the stored list, which can
  // still hold a key for a card that has since left it.
  const activeCount = ALL_GL_KPIS.reduce((n, k) => (activeKpis.includes(k.key) ? n + 1 : n), 0)
  const allActive = ALL_GL_KPIS.every(k => activeKpis.includes(k.key))

  /* Smooth mount / unmount */
  const [mounted, setMounted] = useState(false)
  const [visible, setVisible] = useState(false)
  const timeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null)

  useEffect(() => {
    if (open) {
      setMounted(true)
      if (timeoutRef.current) clearTimeout(timeoutRef.current)
      requestAnimationFrame(() => { requestAnimationFrame(() => setVisible(true)) })
    } else {
      setVisible(false)
      timeoutRef.current = setTimeout(() => setMounted(false), 280)
    }
    return () => { if (timeoutRef.current) clearTimeout(timeoutRef.current) }
  }, [open])

  if (!mounted) return null

  return (
    <>
      <div
        className="fixed inset-0 z-[200] transition-opacity duration-[250ms] ease-in-out"
        style={{ backgroundColor: visible ? 'rgba(0,0,0,0.25)' : 'rgba(0,0,0,0)', pointerEvents: visible ? 'auto' : 'none' }}
        onClick={() => onOpenChange(false)}
      />
      <div
        className="fixed right-0 top-0 bottom-0 z-[200] w-full max-w-[400px] bg-white flex flex-col shadow-2xl transition-transform duration-[280ms] ease-[cubic-bezier(0.32,0.72,0,1)]"
        style={{ transform: visible ? 'translateX(0)' : 'translateX(100%)' }}
      >
        {/* Header */}
        <div className="px-5 pt-5 pb-0 shrink-0">
          <div className="flex items-start justify-between">
            <div className="flex items-start gap-3">
              <div className="w-10 h-10 rounded-xl flex items-center justify-center shrink-0" style={{ backgroundColor: 'hsl(var(--accent))' }}>
                <Sliders className="w-5 h-5" style={{ color: 'hsl(var(--primary))' }} />
              </div>
              <div>
                <h2 className="text-base text-foreground" style={{ fontWeight: 600 }}>Insights</h2>
                <p className="text-13 text-muted-foreground mt-0.5">Manage your ledger KPIs.</p>
              </div>
            </div>
            <button onClick={() => onOpenChange(false)} className="p-1.5 rounded-md hover:bg-muted/50 transition-colors cursor-pointer -mt-0.5 -mr-1">
              <X className="w-4 h-4 text-muted-foreground" />
            </button>
          </div>
          {/* Toggle all */}
          <div className="flex items-center justify-between mt-4 px-1 gap-2">
            <span className="text-xs text-muted-foreground" style={{ fontWeight: 500 }}>{activeCount} of {ALL_GL_KPIS.length} KPIs active</span>
            <div className="flex items-center gap-1.5">
              {onReset && !isDefault && (
                <button
                  onClick={onReset}
                  className="flex items-center gap-1 text-xs px-2.5 py-1.5 rounded-full border border-border bg-slate-50 text-slate-600 hover:bg-muted hover:border-slate-300 transition-all duration-200 cursor-pointer"
                  style={{ fontWeight: 500 }}
                >
                  <RotateCcw className="w-3 h-3" />
                  <span>Reset</span>
                </button>
              )}
              <button
                onClick={() => {
                  const allKeys = ALL_GL_KPIS.map(k => k.key)
                  if (allActive) activeKpis.forEach(k => onToggleKpi(k))
                  else allKeys.filter(k => !activeKpis.includes(k)).forEach(k => onToggleKpi(k))
                }}
                className={cn('flex items-center gap-1.5 text-xs px-3 py-1.5 rounded-full border transition-all duration-200 cursor-pointer',
                  allActive
                    ? 'bg-[#EBF3FF] border-primary/25 text-primary hover:bg-[#DBEAFE] hover:border-primary/40 shadow-sm shadow-primary/10'
                    : activeKpis.length === 0
                    ? 'bg-slate-50 border-border text-slate-400 hover:bg-muted hover:border-slate-300 hover:text-slate-500'
                    : 'bg-slate-50 border-border text-slate-500 hover:bg-[#EBF3FF] hover:border-primary/25 hover:text-primary')}
                style={{ fontWeight: 600 }}
              >
                {allActive ? (<><ToggleRight className="w-4 h-4 text-primary" /><span>All On</span></>)
                  : activeKpis.length === 0 ? (<><ToggleLeft className="w-4 h-4" /><span>All Off</span></>)
                  : (<><ToggleLeft className="w-4 h-4" /><span>Enable All</span></>)}
              </button>
            </div>
          </div>
        </div>

        {/* Search */}
        <div className="px-5 pt-3.5 pb-0 shrink-0">
          <div className="relative">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground/50 pointer-events-none" />
            <input
              placeholder="Search metrics..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full h-10 pl-10 pr-3 rounded-lg border border-border bg-white text-sm text-foreground outline-none focus:border-primary/40 focus:ring-2 focus:ring-primary/10 transition-colors"
            />
          </div>
        </div>

        <div className="border-b border-muted mt-3 shrink-0" />

        {/* Scrollable content */}
        <div className="flex-1 overflow-y-auto px-4 pb-4 scrollbar-thin">
          {categories.length === 0 && (
            <div className="flex flex-col items-center py-12 text-muted-foreground">
              <Search className="w-5 h-5 mb-2 opacity-40" />
              <p className="text-xs text-muted-foreground/60">No metrics found</p>
            </div>
          )}
          {categories.map((cat) => (
            <div key={cat.name} className="mt-5 first:mt-4">
              <div className="flex items-center gap-1.5 mb-2">
                <CategoryIcon category={cat.name} />
                <span className="text-xs text-muted-foreground/70 uppercase tracking-wide" style={{ fontWeight: 600 }}>{cat.name}</span>
              </div>
              <div className="grid grid-cols-2 gap-2">
                {cat.kpis.map((kpi) => {
                  const isActive = activeKpis.includes(kpi.key)
                  const value = computeGlKpiValue(kpi.key, ctx)
                  return (
                    <button
                      key={kpi.key}
                      onClick={() => onToggleKpi(kpi.key)}
                      className={cn('relative text-left rounded-lg border px-3 py-2.5 transition-all duration-150 cursor-pointer group',
                        isActive
                          ? 'border-primary/25 bg-primary/[0.04] shadow-[0_0_0_1px_rgba(10,119,255,0.08)]'
                          : 'border-border/60 bg-white hover:border-border hover:bg-muted/20 hover:shadow-sm')}
                    >
                      <div className="flex items-center justify-between gap-1">
                        <span className={cn('text-xs truncate transition-colors', isActive ? 'text-primary' : 'text-muted-foreground/70')} style={{ fontWeight: 500 }} title={kpi.label}>{kpi.label}</span>
                        <div className="shrink-0">
                          {isActive ? <Check className="w-3.5 h-3.5" style={{ color: 'hsl(var(--primary))' }} />
                            : <Plus className="w-3.5 h-3.5 text-muted-foreground/25 group-hover:text-muted-foreground/50 transition-colors" />}
                        </div>
                      </div>
                      <p className={cn('text-15 mt-1 transition-colors', isActive ? 'text-foreground' : 'text-foreground/80')} style={{ fontWeight: 550 }}>{value}</p>
                    </button>
                  )
                })}
              </div>
            </div>
          ))}
        </div>
      </div>
    </>
  )
}
