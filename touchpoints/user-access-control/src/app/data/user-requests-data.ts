/* ─── User Request row type ─── */
export type RequestAccessLevel = "View" | "Edit" | "Full Access";
export type RequestPriority = "Low" | "Medium" | "High";

export interface UserRequestRow {
  id: string;
  requestedBy: string;
  requestedFor: string; // module name
  reason: string;
  requestedOn: string;
  status: "Accepted" | "Pending" | "Rejected";
  /* ── Enriched fields for detail modal ── */
  email: string;
  role: string;
  accessLevel: RequestAccessLevel;
  priority: RequestPriority;
  /** Specific permission IDs being requested (from PERMISSION_MODULES) */
  requestedPermissionIds: string[];
  /** What the user currently has access to in this module */
  currentAccess: string[];
  /** Reviewer info (for resolved requests) */
  reviewedBy?: string;
  reviewedOn?: string;
  reviewNotes?: string;
}

