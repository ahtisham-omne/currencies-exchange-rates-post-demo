/* ─────────────────────────── PALETTE ─────────────────────────── */

const SANDBOX_VIOLET = "#524BE0";
const SANDBOX_WASH_BG = "#F2F1FF";
const SANDBOX_WASH_TEXT = "#3F3A9A";

/* ─────────────────────────── HELPERS ─────────────────────────── */

const todayIso = (offsetDays = 0): string => {
  const d = new Date();
  d.setHours(0, 0, 0, 0);
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10);
};

/* ─────────────────────────── DRAFT LINE ─────────────────────────── */

/** One editable line inside the modal — represents a single
    vendor-allocation generated by `buildRecommendations` for one item.
    `key` is composite (`itemCode::vendorId`) so two recommendations
    for different items going to the same vendor don't collide; the
    vendor-grouping step keys them by vendorId at the parent level. */
interface DraftLine {
  key: string;
  itemCode: string;
  itemName: string;
  itemImage: string;
  category: string;
  baseUom: string;
  purchaseUom: string;
  /** The PlannerItem record — kept by reference so snapQty / pricing
      rules can be re-applied per-row without round-tripping. */
  item: PlannerItem;
  /** The vendor that this allocation is bound to. */
  vendor: PlannerVendor;
  /** Editable: order qty in the item's `baseUom`. */
  qty: number;
  /** Editable: arrival offset days from today. Derived from the
      vendor's `leadTimeDays` at seed time; the buyer can push out or
      pull in within the lead-time floor when overriding. */
  arrivalDays: number;
  /** Per-line on/off — buyer can drop one allocation without taking
      the whole vendor group out. */
  included: boolean;
  /** Most-recent qty-snap hint (e.g. "Snapped to multiple of 12") so
      the row can surface inline corrections without a separate toast. */
  qtyHint: string | null;
}

/* ─────────────────────────── INPUT SHAPE ─────────────────────────── */

/** What the host (PODemands) hands in. Each entry is one in-scope
    item that buildRecommendations was run against. Items with empty
    `recommendations` still show up if they carry conflicts — that's
    decision-support too (the buyer sees why nothing was teed up). */
export interface ItemRecommendationInput {
  item: PlannerItem;
  recommendations: Recommendation[];
  conflicts: RecommendationConflict[];
}

export interface RecommendedPOsModalProps {
  open: boolean;
  onClose: () => void;
  /** Every in-scope item from the post-Apply listing, with its
      pre-computed recommendation + conflicts. Empty list = nothing to
      recommend right now. */
  inputs: ItemRecommendationInput[];
}

/* ─────────────────────────── COMPONENT ─────────────────────────── */

export default function RecommendedPOsModal({
  open,
  onClose,
  inputs,
}: RecommendedPOsModalProps) {
  /* Seed `lines` from `inputs` whenever the modal opens. We don't
     reseed on every prop change because the buyer may have edited
     qty / arrival in-place; re-seeding mid-session would drop those
     edits. The dependency on `open` is what gates the reset. */
  const [lines, setLines] = useState<DraftLine[]>([]);
  const [dismissedConflictKeys, setDismissedConflictKeys] = useState<Set<string>>(
    () => new Set(),
  );
  /* Tracks if the buyer has acknowledged opening the modal — purely
     visual; gates the empty-state copy versus the populated one. */

  useEffect(() => {
    if (!open) return;
    const seeded: DraftLine[] = [];
    for (const input of inputs) {
      for (const rec of input.recommendations) {
        const vendor = input.item.qualifiedVendors.find((v) => v.vendorId === rec.vendorId);
        if (!vendor) continue;
        seeded.push({
          key: `${input.item.itemCode}::${rec.vendorId}`,
          itemCode: input.item.itemCode,
          itemName: input.item.itemName,
          itemImage: input.item.itemImage,
          category: input.item.category,
          baseUom: input.item.baseUom,
          purchaseUom: input.item.purchaseUom,
          item: input.item,
          vendor,
          qty: rec.qty,
          arrivalDays: rec.arrivalDays,
          included: true,
          qtyHint: null,
        });
      }
    }
    setLines(seeded);
    setDismissedConflictKeys(new Set());
  }, [open, inputs]);

  /* ─── Conflicts surface ──────────────────────────────────────────
     Conflicts arrive scoped to a single item; we render them grouped
     above their parent vendor's card. Dismissal is per-conflict and
     scoped to this open-session — closing + reopening the modal
     restores them. */
  const conflictEntries = useMemo(() => {
    const out: Array<{ itemCode: string; itemName: string; index: number; conflict: RecommendationConflict }> = [];
    for (const input of inputs) {
      input.conflicts.forEach((c, i) => {
        /* Drop "no-deficit" — it's the happy path (projection stays
           above min). The buyer doesn't need a banner telling them
           there's nothing to do; the absence of a row already says
           that. */
        if (c.kind === "no-deficit") return;
        out.push({
          itemCode: input.item.itemCode,
          itemName: input.item.itemName,
          index: i,
          conflict: c,
        });
      });
    }
    return out.filter((e) => !dismissedConflictKeys.has(`${e.itemCode}::${e.index}`));
  }, [inputs, dismissedConflictKeys]);

  /* ─── Vendor grouping ────────────────────────────────────────────
     Collapse the flat line list into per-vendor groups so the buyer
     reads "one card per draft PO" — same per-vendor framing the
     Sandbox uses for proposed POs. Each vendor group totals its
     included lines for the per-card subtotal. */
  const groupedByVendor = useMemo(() => {
    const map = new Map<string, { vendor: PlannerVendor; lines: DraftLine[] }>();
    for (const l of lines) {
      const existing = map.get(l.vendor.vendorId);
      if (existing) existing.lines.push(l);
      else map.set(l.vendor.vendorId, { vendor: l.vendor, lines: [l] });
    }
    /* Sort vendor groups by name for stable order. */
    return Array.from(map.values()).sort((a, b) =>
      a.vendor.vendorName.localeCompare(b.vendor.vendorName),
    );
  }, [lines]);

  /* Count of vendors that will actually generate a draft PO — only
     vendor groups with at least one included line count. Drives the
     Execute button label + disabled state. */
  const includedVendorCount = useMemo(() => {
    let n = 0;
    for (const g of groupedByVendor) {
      if (g.lines.some((l) => l.included)) n++;
    }
    return n;
  }, [groupedByVendor]);

  /* Total line count (across vendors) — quieter "X lines across Y
     vendors" caption helps the buyer scan the size of the batch. */
  const includedLineCount = useMemo(
    () => lines.filter((l) => l.included).length,
    [lines],
  );

  /* ─── Mutations ─────────────────────────────────────────────── */

  const updateLine = (key: string, patch: Partial<DraftLine>) => {
    setLines((prev) => prev.map((l) => (l.key === key ? { ...l, ...patch } : l)));
  };

  const onQtyBlur = (key: string, raw: number) => {
    const line = lines.find((l) => l.key === key);
    if (!line) return;
    const { snapped, hint } = snapQty(
      raw,
      line.item.moq,
      line.item.maxOrderQty,
      line.item.orderMultiples,
    );
    updateLine(key, { qty: snapped, qtyHint: hint });
  };

  const onArrivalChange = (key: string, iso: string) => {
    if (!iso) return;
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const target = new Date(iso);
    target.setHours(0, 0, 0, 0);
    const days = Math.max(0, Math.round((target.getTime() - today.getTime()) / 86_400_000));
    updateLine(key, { arrivalDays: days });
  };

  const toggleIncluded = (key: string) => {
    setLines((prev) => prev.map((l) => (l.key === key ? { ...l, included: !l.included } : l)));
  };

  const removeLine = (key: string) => {
    setLines((prev) => prev.filter((l) => l.key !== key));
  };

  /* ─── Execute — create Draft POs grouped per vendor ─────────────
     Mirrors the Sandbox's `handleExecute` pattern: one
     `createPOFromVendorCheckout` call per vendor group with every
     included line bundled as `lineItems`. The PO landing page
     receives each batch grouped, which matches the buyer's mental
     model ("one PO per vendor"). */
  const handleExecute = () => {
    if (includedLineCount === 0) return;
    let createdCount = 0;
    for (const g of groupedByVendor) {
      const included = g.lines.filter((l) => l.included);
      if (included.length === 0) continue;
      const orderFlowLines = included.map((l) => {
        const arrivalIso = todayIso(l.arrivalDays);
        const shipByIso = todayIso(Math.max(0, l.arrivalDays - 1));
        const unit = effectivePrice(l.vendor.unitPrice, l.vendor.pricingRules, l.qty);
        return {
          id: `rec-${l.itemCode}-${l.vendor.vendorId}-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
          itemNumber: l.itemCode,
          descriptiveName: l.itemName,
          image: l.itemImage,
          unitPrice: unit,
          vendorQty: l.qty,
          vendorUOM: l.purchaseUom,
          vendorUOMQty: 1,
          quantity: l.qty,
          defaultUOM: l.baseUom,
          discount: 0,
          shipByDate: shipByIso,
          shipmentMethod: "Standard",
          needByDate: arrivalIso,
          inboundLocation: "Default",
          category: l.category,
        };
      });
      createPOFromVendorCheckout(
        g.vendor.vendorName,
        orderFlowLines,
        `Procurement Planning · Recommend POs (${included.length} line${included.length === 1 ? "" : "s"})`,
        [],
        // Planning prices are USD; the PO converts them to the vendor's currency.
        "USD",
      );
      createdCount++;
    }
    toast.success(
      `${createdCount} draft PO${createdCount === 1 ? "" : "s"} created`,
      { description: "Review in the Purchase Orders tab." },
    );
    onClose();
  };

  /* ─────────────────────────── RENDER ─────────────────────────── */

  return (
    <Dialog open={open} onOpenChange={(v) => { if (!v) onClose(); }}>
      <DialogContent
        className={`${MODAL_SIZE_CLASS} p-0 gap-0 overflow-hidden flex flex-col`}
        style={{ fontFamily: FONT }}
      >
        {/* ───── Header — Sandbox-violet wash signals planning mode ───── */}
        <header
          className="flex items-center gap-3 px-5 py-3 border-b shrink-0"
          style={{ backgroundColor: SANDBOX_WASH_BG, borderColor: "rgba(82,75,224,0.18)" }}
        >
          <div
            className="flex items-center justify-center size-8 rounded-md shrink-0"
            style={{ backgroundColor: "white", border: `1px solid rgba(82,75,224,0.25)` }}
          >
            <Sparkles className="size-4" style={{ color: SANDBOX_VIOLET }} />
          </div>
          <div className="min-w-0 flex-1">
            <DialogTitle
              className="text-[14px] leading-tight"
              style={{ fontWeight: 600, color: SANDBOX_WASH_TEXT }}
            >
              Recommend POs
            </DialogTitle>
            <DialogDescription
              className="text-[11.5px] mt-0.5 leading-snug"
              style={{ color: "rgba(63,58,154,0.85)" }}
            >
              Drafts grouped by vendor — review, edit, and Execute when ready.
            </DialogDescription>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="size-8 inline-flex items-center justify-center rounded-md hover:bg-white/60 cursor-pointer transition-colors"
            style={{ color: SANDBOX_WASH_TEXT }}
            aria-label="Close"
          >
            <X className="size-4" />
          </button>
        </header>

        {/* ───── Body — scrolls; vendors stack vertically as cards ───── */}
        <div className="flex-1 overflow-y-auto px-5 py-3 flex flex-col gap-3">
          {/* Empty state */}
          {lines.length === 0 && conflictEntries.length === 0 && (
            <div className="flex flex-col items-center justify-center py-16 px-6 text-center">
              <div
                className="flex items-center justify-center size-16 rounded-full"
                style={{ backgroundColor: "hsl(var(--secondary))" }}
              >
                <CheckCircle2
                  className="size-7"
                  style={{ color: "hsl(var(--muted-foreground))", opacity: 0.6 }}
                  strokeWidth={1.5}
                />
              </div>
              <span
                className="mt-4 text-[13px]"
                style={{ color: "hsl(var(--foreground))", fontWeight: 500 }}
              >
                Nothing to recommend right now
              </span>
              <span
                className="mt-1 text-[12px] max-w-xs"
                style={{ color: "hsl(var(--muted-foreground))" }}
              >
                Every in-scope item's projection stays above its min level across the
                horizon. Adjust your scope or wait for new demand to land.
              </span>
            </div>
          )}

          {/* Conflict banners — render above the per-vendor cards so
             the buyer reads the constraints before scanning the
             draft list. Each is one row of the same shape Sandbox
             uses for its conflict strip. */}
          {conflictEntries.length > 0 && (
            <div className="flex flex-col gap-2">
              {conflictEntries.map(({ itemCode, itemName, index, conflict }) => (
                <ConflictBanner
                  key={`${itemCode}::${index}`}
                  itemCode={itemCode}
                  itemName={itemName}
                  conflict={conflict}
                  onDismiss={() =>
                    setDismissedConflictKeys((prev) => {
                      const next = new Set(prev);
                      next.add(`${itemCode}::${index}`);
                      return next;
                    })
                  }
                />
              ))}
            </div>
          )}

          {/* Per-vendor draft cards. */}
          {groupedByVendor.map((g) => (
            <VendorCard
              key={g.vendor.vendorId}
              vendor={g.vendor}
              lines={g.lines}
              onLineToggle={toggleIncluded}
              onLineQtyBlur={onQtyBlur}
              onLineArrivalChange={onArrivalChange}
              onLineRemove={removeLine}
            />
          ))}
        </div>

        {/* ───── Sticky footer — Execute action with count badge ───── */}
        <footer
          className="flex items-center justify-between gap-3 px-6 py-3 border-t shrink-0"
          style={{ borderColor: "hsl(var(--border))", backgroundColor: "hsl(var(--secondary))" }}
        >
          <div
            className="text-[11.5px] flex items-center gap-2"
            style={{ color: "hsl(var(--muted-foreground))" }}
          >
            <Info className="size-3" />
            {includedLineCount === 0
              ? "Nothing checked — toggle a line back in to enable Execute."
              : `${includedLineCount} line${includedLineCount === 1 ? "" : "s"} across ${includedVendorCount} vendor${includedVendorCount === 1 ? "" : "s"} ready to draft.`}
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" size="sm" className="h-9 px-4" onClick={onClose}>
              Cancel
            </Button>
            <Button
              size="sm"
              className="h-9 px-4 gap-1.5"
              disabled={includedLineCount === 0}
              onClick={handleExecute}
              style={
                includedLineCount === 0
                  ? undefined
                  : { backgroundColor: SANDBOX_VIOLET, color: "white" }
              }
            >
              <Send className="size-3.5" />
              Execute ({includedVendorCount} PO{includedVendorCount === 1 ? "" : "s"})
            </Button>
          </div>
        </footer>
      </DialogContent>
    </Dialog>
  );
}

/* ═══════════════════════════════════════════════════════════════
   CONFLICT BANNER
   ───────────────────────────────────────────────────────────────
   One row per surfaced conflict. Visual language mirrors the
   Sandbox conflict strip so the two surfaces feel like one.
   ═══════════════════════════════════════════════════════════════ */

function ConflictBanner({
  itemCode,
  itemName,
  conflict,
  onDismiss,
}: {
  itemCode: string;
  itemName: string;
  conflict: RecommendationConflict;
  onDismiss: () => void;
}) {
  /* Different conflict kinds carry different tone weights. Hard
     blockers (no-qualified-vendors) get an amber tone; informational
     (moq-overshoot, vendor-late) get a softer slate tone. */
  const isHardBlock = conflict.kind === "no-qualified-vendors" || conflict.kind === "uncovered";
  const tone = isHardBlock
    ? { bg: "#FFF7ED", border: "#FED7AA", fg: "#C2410C", iconBg: "#FFEDD5" }
    : { bg: "#F8FAFC", border: "#E2E8F0", fg: "#475569", iconBg: "#F1F5F9" };
  return (
    <div
      className="rounded-md border flex items-start gap-3 px-3 py-2.5"
      style={{ backgroundColor: tone.bg, borderColor: tone.border }}
    >
      <div
        className="size-6 rounded-md flex items-center justify-center shrink-0 mt-0.5"
        style={{ backgroundColor: tone.iconBg }}
      >
        <AlertTriangle className="size-3.5" style={{ color: tone.fg }} />
      </div>
      <div className="flex-1 min-w-0 flex flex-col gap-0.5">
        <span
          className="text-[11.5px] uppercase tracking-wider"
          style={{ fontWeight: 600, color: tone.fg, letterSpacing: "0.04em" }}
        >
          {itemCode} · {itemName.split(" — ")[0]}
        </span>
        <span className="text-[12px] leading-snug" style={{ color: tone.fg, fontWeight: 500 }}>
          {conflict.message}
        </span>
      </div>
      <button
        type="button"
        onClick={onDismiss}
        className="size-6 inline-flex items-center justify-center rounded-md hover:bg-white/70 cursor-pointer transition-colors"
        style={{ color: tone.fg }}
        aria-label="Dismiss"
      >
        <X className="size-3" />
      </button>
    </div>
  );
}

/* ═══════════════════════════════════════════════════════════════
   VENDOR CARD
   ───────────────────────────────────────────────────────────────
   One card per vendor — header strip with vendor name + lead time
   + on-time rating + a per-card subtotal. Body lists each
   recommended line with inline qty + ship-by editors.
   ═══════════════════════════════════════════════════════════════ */

function VendorCard({
  vendor,
  lines,
  onLineToggle,
  onLineQtyBlur,
  onLineArrivalChange,
  onLineRemove,
}: {
  vendor: PlannerVendor;
  lines: DraftLine[];
  onLineToggle: (key: string) => void;
  onLineQtyBlur: (key: string, raw: number) => void;
  onLineArrivalChange: (key: string, iso: string) => void;
  onLineRemove: (key: string) => void;
}) {
  /* Subtotal = sum(effectivePrice * qty) for every INCLUDED line. */
  const subtotal = useMemo(() => {
    let s = 0;
    for (const l of lines) {
      if (!l.included) continue;
      const unit = effectivePrice(vendor.unitPrice, vendor.pricingRules, l.qty);
      s += unit * l.qty;
    }
    return s;
  }, [lines, vendor]);
  const includedCount = lines.filter((l) => l.included).length;

  return (
    <div
      className="rounded-lg border bg-card overflow-hidden"
      style={{ borderColor: "hsl(var(--border))" }}
    >
      {/* Vendor strip — single visual row. Name + meta on one line so
         the strip stays compact even when the vendor name is long. */}
      <div
        className="flex items-center justify-between gap-3 px-4 py-2 border-b"
        style={{ borderColor: "hsl(var(--border))", backgroundColor: "hsl(var(--secondary))" }}
      >
        <div className="min-w-0 flex items-baseline gap-2 flex-wrap">
          <span
            className="text-[13px] truncate shrink-0"
            style={{ fontWeight: 600, color: "hsl(var(--foreground))" }}
          >
            {vendor.vendorName}
          </span>
          <span
            className="text-[11px] truncate"
            style={{ color: "hsl(var(--muted-foreground))" }}
          >
            {vendor.leadTimeDays}d lead · ${vendor.unitPrice.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}/unit · {vendor.onTimeRating}% on-time
          </span>
        </div>
        <div className="flex items-center gap-3 shrink-0">
          <span
            className="text-[11px] tabular-nums"
            style={{ color: "hsl(var(--muted-foreground))" }}
          >
            {includedCount}/{lines.length}
          </span>
          <span
            className="text-[13px] tabular-nums"
            style={{ fontWeight: 600, color: "hsl(var(--foreground))" }}
          >
            ${subtotal.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
          </span>
        </div>
      </div>

      {/* Lines */}
      <div className="flex flex-col">
        {lines.map((l, idx) => (
          <DraftLineRow
            key={l.key}
            line={l}
            divider={idx < lines.length - 1}
            vendor={vendor}
            onToggle={() => onLineToggle(l.key)}
            onQtyBlur={(raw) => onLineQtyBlur(l.key, raw)}
            onArrivalChange={(iso) => onLineArrivalChange(l.key, iso)}
            onRemove={() => onLineRemove(l.key)}
          />
        ))}
      </div>
    </div>
  );
}

/* ═══════════════════════════════════════════════════════════════
   DRAFT LINE ROW — compact single-row editor
   ───────────────────────────────────────────────────────────────
   6-column CSS grid keeps every line aligned regardless of item-
   name length: checkbox · item info (flexes) · qty input + UoM ·
   ship-by date · per-line subtotal · remove. No vertical label
   stacking, no helper-text rows under each input — the layout
   stays a clean single row so a vendor card with many lines is
   still scannable.

   The qty-snap hint (when there is one) renders inline under the
   item name in subtle slate so the buyer doesn't lose it; the
   ship-by arrival days render inline next to the date input.
   ═══════════════════════════════════════════════════════════════ */

function DraftLineRow({
  line,
  divider,
  vendor,
  onToggle,
  onQtyBlur,
  onArrivalChange,
  onRemove,
}: {
  line: DraftLine;
  divider: boolean;
  vendor: PlannerVendor;
  onToggle: () => void;
  onQtyBlur: (raw: number) => void;
  onArrivalChange: (iso: string) => void;
  onRemove: () => void;
}) {
  /* Controlled draft qty — commits via onQtyBlur (snapQty enforces
     MOQ / multiples / max). The buyer sees the typed value until
     blur or Enter; snapping happens once they commit. */
  const [draftQty, setDraftQty] = useState<string>(String(line.qty));
  useEffect(() => {
    setDraftQty(String(line.qty));
  }, [line.qty]);

  const arrivalIso = useMemo(() => {
    const d = new Date();
    d.setHours(0, 0, 0, 0);
    d.setDate(d.getDate() + line.arrivalDays);
    return d.toISOString().slice(0, 10);
  }, [line.arrivalDays]);

  /* Per-line subtotal — same math the vendor card uses to aggregate
     subtotals, surfaced inline so the buyer reads it next to the
     qty + date controls they're editing. */
  const lineTotal = useMemo(
    () => effectivePrice(vendor.unitPrice, vendor.pricingRules, line.qty) * line.qty,
    [vendor, line.qty],
  );

  return (
    <div
      className={`grid items-center gap-3 px-4 py-2 ${divider ? "border-b" : ""}`}
      style={{
        borderColor: "hsl(var(--border))",
        opacity: line.included ? 1 : 0.55,
        gridTemplateColumns:
          "auto minmax(0, 1fr) auto auto minmax(72px, auto) auto",
      }}
    >
      {/* Per-line include checkbox */}
      <Checkbox checked={line.included} onCheckedChange={onToggle} />

      {/* Item info — code on top, name truncated below. When there's
         an active qty-snap hint, surface it inline as a tiny third
         line so the buyer doesn't miss the correction. */}
      <div className="min-w-0 flex flex-col gap-0">
        <span
          className="text-[12.5px] truncate"
          style={{ fontWeight: 600, color: "hsl(var(--foreground))" }}
        >
          {line.itemCode}
        </span>
        <span
          className="text-[11px] truncate"
          style={{ color: "hsl(var(--muted-foreground))" }}
          title={line.itemName}
        >
          {line.itemName}
        </span>
        {line.qtyHint && (
          <span
            className="text-[10.5px] truncate mt-0.5"
            style={{ color: "#C2410C", fontWeight: 500 }}
          >
            {line.qtyHint}
          </span>
        )}
      </div>

      {/* Qty input + base UoM suffix — inline, no label */}
      <div className="flex items-center gap-1.5 shrink-0">
        <Input
          type="number"
          inputMode="numeric"
          min={1}
          value={draftQty}
          onChange={(e) => setDraftQty(e.target.value)}
          onBlur={() => {
            const n = Number(draftQty);
            onQtyBlur(Number.isFinite(n) ? n : line.qty);
          }}
          onKeyDown={(e) => {
            if (e.key === "Enter") {
              e.preventDefault();
              const n = Number((e.target as HTMLInputElement).value);
              onQtyBlur(Number.isFinite(n) ? n : line.qty);
            }
          }}
          className="h-8 w-20 text-right tabular-nums text-[12px]"
          disabled={!line.included}
          title={`Multiple of ${line.item.orderMultiples}, MOQ ${line.item.moq}, max ${line.item.maxOrderQty}`}
        />
        <span
          className="text-[11px] shrink-0"
          style={{ color: "hsl(var(--muted-foreground))", fontWeight: 500 }}
        >
          {line.baseUom}
        </span>
      </div>

      {/* Ship-by date — inline arrival hint to the right */}
      <div className="flex items-center gap-1.5 shrink-0">
        <SystemDatePicker
          value={arrivalIso}
          onChange={onArrivalChange}
          disabled={!line.included}
          className="w-[160px]"
          placeholder="Pick ship-by"
        />
        <span
          className="text-[10.5px] whitespace-nowrap shrink-0"
          style={{ color: "hsl(var(--muted-foreground))" }}
          title="Arrival offset from today"
        >
          +{line.arrivalDays}d
        </span>
      </div>

      {/* Per-line subtotal */}
      <span
        className="text-[12.5px] tabular-nums text-right whitespace-nowrap"
        style={{ fontWeight: 600, color: "hsl(var(--foreground))" }}
      >
        ${lineTotal.toLocaleString(undefined, {
          minimumFractionDigits: 2,
          maximumFractionDigits: 2,
        })}
      </span>

      {/* Remove */}
      <button
        type="button"
        onClick={onRemove}
        className="size-7 inline-flex items-center justify-center rounded-md cursor-pointer hover:bg-rose-50 transition-colors shrink-0"
        aria-label="Remove this draft line"
        style={{ color: "#B91C1C" }}
      >
        <Trash2 className="size-3.5" />
      </button>
    </div>
  );
}
