/** Convert a URL segment to a human label, falling back to title-case. */
export function segmentToLabel(segment: string): string {
  return (
    SEGMENT_LABELS[segment] ||
    segment
      .replace(/-/g, " ")
      .replace(/\b\w/g, (c) => c.toUpperCase())
  );
}
