import { describe, it, expect } from 'vitest'
import { ALL_GL_KPIS, DEFAULT_GL_KPIS, computeGlKpiValue, glKpiTarget, type GlKpiCtx, type GlKpiDefinition } from '../components/GlInsights'

const def = (key: string): GlKpiDefinition => {
  const found = ALL_GL_KPIS.find(k => k.key === key)
  if (!found) throw new Error(`no KPI definition for ${key}`)
  return found
}

const ctx = (over: Partial<GlKpiCtx['stats']> = {}): GlKpiCtx => ({
  stats: {
    totalActivity: 1234567.89,
    postingCount: 1434,
    manualEntryCount: 12,
    largestPosting: { jeNumber: 'JE-0042', label: 'JE-0042', value: 88000 },
    ...over,
  },
  base: 'USD',
  periodLabel: 'Aug FY2026',
})

// The ledger is a stream of postings, not a set of balances, so every card here
// describes activity inside the selected accounting period. The tooltips are the
// user's dictation - a reworded card is a changed promise, so pinned verbatim.
describe('KPI copy', () => {
  it('says of each card that it covers this period', () => {
    // Mahad's copy, 2026-10-14.
    expect(def('total_activity').label).toBe('Total debits')
    expect(def('total_activity').tooltip).toBe('Sum of all debits posted in the selected period, which matches total credits.')
    expect(def('postings').label).toBe('Postings')
    expect(def('postings').tooltip).toBe('Number of debit and credit lines posted in the selected period.')
    expect(def('largest_posting').label).toBe('Largest posting')
    expect(def('largest_posting').tooltip).toBe('Largest single debit or credit line posted in the selected period.')
    expect(def('manual_journal_entries').label).toBe('Manual journal entries')
    expect(def('manual_journal_entries').tooltip).toBe('Journal entries created directly in the general ledger rather than generated by another module.')
  })

  it('offers no card that double-entry already fixes', () => {
    // Total debit and total credit are always equal and net movement across the
    // whole ledger is always zero, so a card stating any of them can never be
    // worth a glance. Activity is stated once instead.
    const keys = ALL_GL_KPIS.map(k => k.key)
    expect(keys).not.toContain('total_debit')
    expect(keys).not.toContain('total_credit')
    expect(keys).not.toContain('net_movement')
    expect(keys).not.toContain('top_account')
  })

  it('shows every card it defines, since none of them can be empty', () => {
    expect(DEFAULT_GL_KPIS).toEqual(ALL_GL_KPIS.map(k => k.key))
  })

  it('uses no em dashes and no retired vocabulary', () => {
    const BANNED = ['group', 'begin-total', 'end-total', 'heading', 'bracket', 'totaling']
    for (const k of ALL_GL_KPIS) {
      for (const s of [k.label, k.subtitle, k.tooltip ?? '']) {
        expect(s).not.toContain('—')
        for (const word of BANNED) expect(s.toLowerCase(), s).not.toContain(word)
      }
    }
  })
})

// Figures print every digit: abbreviating to "$1.2M" rounded away the difference
// between a card and the ledger beneath it, so the two could not be reconciled
// by eye even when they agreed exactly.
describe('values', () => {
  it('prints money in full, never abbreviated to millions', () => {
    expect(computeGlKpiValue('total_activity', ctx())).toContain('1,234,568')
    expect(computeGlKpiValue('total_activity', ctx())).not.toMatch(/[KMB]/)
    expect(computeGlKpiValue('largest_posting', ctx())).toContain('88,000')
  })

  it('prints counts as plain numbers', () => {
    expect(computeGlKpiValue('postings', ctx())).toBe('1,434')
    expect(computeGlKpiValue('manual_journal_entries', ctx())).toBe('12')
  })

  it('says nothing rather than $0.00 when the period holds no postings', () => {
    expect(computeGlKpiValue('largest_posting', ctx({ largestPosting: null }))).toBe('-')
  })

  it('counts a manual entry once however many lines it carries', () => {
    // The page counts distinct jeNumbers, so this stays a document count.
    expect(computeGlKpiValue('manual_journal_entries', ctx({ manualEntryCount: 3, postingCount: 40 })))
      .toBe('3')
  })
})

// Only the largest posting opens anything, and it opens the entry rather than
// the account, because the entry is what the reader wants to inspect.
describe('navigation', () => {
  it('opens the biggest entry of the period', () => {
    expect(glKpiTarget('largest_posting', ctx())).toEqual({ kind: 'entry', id: 'JE-0042' })
  })

  it('opens nothing when there is no biggest entry to open', () => {
    expect(glKpiTarget('largest_posting', ctx({ largestPosting: null }))).toBeNull()
  })

  it('marks as navigable exactly the cards that resolve to a target', () => {
    for (const k of ALL_GL_KPIS) {
      expect(glKpiTarget(k.key, ctx()) !== null, k.key).toBe(!!k.navigable)
    }
  })
})
