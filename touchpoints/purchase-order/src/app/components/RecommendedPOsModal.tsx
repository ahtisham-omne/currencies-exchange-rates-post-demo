/* ═══════════════════════════════════════════════════════════════
   RECOMMENDED POs — batch surface for the Procurement Planning tab
   ───────────────────────────────────────────────────────────────
   Materialises the Phase 6 recommendation engine across every
   in-scope item on the All-Demand listing. The buyer clicks
   "Recommend POs" once; this surface tees up the minimum efficient
   set of draft POs grouped by vendor, surfaces any cross-rule
   conflicts inline, lets the buyer edit qty / ship-by per line,
   and creates draft POs (never auto-executes) via the same
   `createPOFromVendorCheckout` path the Sandbox's Execute uses.

   Reuse map:
     · `buildRecommendations`, `snapQty`, `RecommendationConflict`
       → `./procurementRecommendations` (single source of truth for
         what "the system recommends" means; identical math to the
         Sandbox's per-item Recommend POs flow).
     · `createPOFromVendorCheckout`, `effectivePrice`
       → existing PO + projection layers (no PO-creation rewrite).
     · Sandbox-violet palette (`#524BE0` / `#F2F1FF` / `#3F3A9A`)
       → matches the planning-mode signal used elsewhere; the
         buyer reads "this is a planning workspace" without
         further explanation.

   What this surface is NOT:
     · A scope picker — the parameter set on the page already does
       that. This surface uses the same in-scope list.
     · An auto-executor — Execute creates Draft POs, never sends.
     · A vendor swap — qualified-vendor alternatives are surfaced
       in the conflict banner; the per-row edit panel covers
       qty + ship-by but not vendor reassignment.
   ═══════════════════════════════════════════════════════════════ */

